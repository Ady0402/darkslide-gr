#!/usr/bin/env python3
"""Build only ARM code fragments. Never reads or generates a firmware image.

Run from a source checkout with LLVM clang available. --check reconstructs into
memory and compares byte-for-byte without replacing shipped resources.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys

APP = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(APP))
from darkslide import film_inplace_cache, gr3x_inplace
from darkslide.arm_compiler import resolve_clang
from darkslide.film_arm_assemble import assemble
from darkslide.film_precompiled import source_key


def build():
    families = {}
    for family, module in [('GRIII-2.10-v29', film_inplace_cache), ('GRIIIx-1.60-v29', gr3x_inplace)]:
        entries = {}; combinations = {}
        for mask in range(1, 16):
            calls = []
            def compile_one(source, base):
                blob = assemble(source, base)
                key = source_key(source, base)
                row = dict(size=len(blob), sha256=hashlib.sha256(blob).hexdigest(), hex=blob.hex())
                if key in entries and entries[key] != row:
                    raise ValueError('non-deterministic assembly')
                entries[key] = row; calls.append(key)
                return blob
            addresses, code = module.build_code(mask, compile_one)
            combinations[str(mask)] = dict(calls=calls, addresses=addresses,
                final_sizes={role: len(blob) for role,blob in code.items()})
        families[family] = dict(layout=module.LAYOUT, official_payload_sha256=module.SHA,
                               entries=entries, combinations=combinations)
    # Record transitive source producers, including the assembler, in the artifact.
    names = ['film_inplace_cache.py','gr3x_inplace.py','film_arm_assemble.py',
             'film_scheme_c.py','gr3x_inplace_support.py','_vendor/gr3_four_curve_hooks.py',
             '_vendor/gr3_film_hooks.py']
    sources = {name:hashlib.sha256((APP/'darkslide'/name).read_bytes()).hexdigest()
               for name in names }
    version = subprocess.run([resolve_clang(),'--version'],capture_output=True,text=True,check=True).stdout.splitlines()[0]
    return dict(schema=1, compiler=version, target='armv7a-none-eabi', sources=sources,
                provenance='Distributed Darkslide sources; MIT-derived hooks retain app/darkslide/_vendor notices; no original firmware bytes.',
                families=families)


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    raw=(json.dumps(build(),sort_keys=True,indent=2)+'\n').encode()
    path=APP/'darkslide/data/film_arm_v1.json'
    pin=APP/'darkslide/film_precompiled_pin.py'
    digest=hashlib.sha256(raw).hexdigest()
    pin_raw=("# Generated by tools/build_film_arm_bundle.py; reviewed with the source bundle.\nBUNDLE_SHA256 = %r\n" % digest).encode()
    if args.check:
        if path.read_bytes()!=raw or pin.read_bytes()!=pin_raw:raise SystemExit('bundle differs; inspect source/compiler version')
    else:
        path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(raw);pin.write_bytes(pin_raw)
    print(json.dumps(dict(sha256=digest,size=len(raw),checked=args.check)))

if __name__=='__main__':main()
